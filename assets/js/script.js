/* ==========================================================================
   [3] وظيفة (استرجاع نسخة احتياطية للنظام)
   - الوظيفة: تفتح مدير الملفات في الجوال أو الكمبيوتر لاختيار ملف النسخة الاحتياطية.
   - طريقة التعديل مستقبلاً:
     * لإضافة صيغ ملفات جديدة: عدّل سطر (input.accept = '.json,.bak';).
     * لقراءة محتوى الملف وحفظه في النظام: اكتب كود القراءة داخل شرط (if (file))
       مكان سطر (alert).
   ========================================================================== */
document.getElementById('restoreBackupLink')?.addEventListener('click', function(event) {
    event.preventDefault();

    const input = document.createElement('input');
    input.type = 'file';
    input.accept = '.json,.bak'; // الصيغ المسموح برفعها للنسخ الاحتياطية

    input.onchange = function(e) {
        const file = e.target.files[0];
        if (file) {
            alert(`تم اختيار ملف النسخة الاحتياطية: (${file.name})\nجاري استعادة بيانات نظام راسخ...`);
        }
    };

    input.click();
});
